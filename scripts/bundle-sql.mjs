// Concatenates supabase/migrations/*.sql (in order) into supabase/setup.sql so a beginner can
// paste ONE file into the Supabase SQL Editor. Run: npm run db:bundle
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "supabase", "migrations");

const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const header = [
  "-- =====================================================================",
  "-- Elevate Campus Hub — full database setup (generated by `npm run db:bundle`)",
  "-- Paste this whole file into Supabase > SQL Editor > New query > Run.",
  "-- Run it ONCE on a fresh project. Do not edit; edit supabase/migrations/* instead.",
  "-- =====================================================================",
  "",
].join("\n");

const body = files
  .map((f) => `-- >>>>>>>>>> ${f} <<<<<<<<<<\n${readFileSync(join(dir, f), "utf8").trim()}\n`)
  .join("\n");

writeFileSync(join(root, "supabase", "setup.sql"), `${header}\n${body}`);
console.log(`Wrote supabase/setup.sql from ${files.length} migration files: ${files.join(", ")}`);
